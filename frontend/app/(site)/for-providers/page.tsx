function FeatureTable({ title, id, items }: { title: string; id: string; items: Feature[] }) {
  return (
    <section id={id} className={styles.section} aria-labelledby={`${id}-title`}>
      <h2 id={`${id}-title`}>{title}</h2>
      <table className={styles.table} aria-labelledby={`${id}-title`}>
        <thead>
          <tr><th scope="col">Возможность</th><th scope="col">Как пользоваться</th></tr>
        </thead>
        <tbody>
          {items.map(({ name, description, href }) => (
            <tr key={name}>
              <th scope="row">
                {href ? <Link href={href} prefetch={false}>{name}</Link> : name}
              </th>
              <td>{description}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </section>
  );
}

