export function messengerWelcomeMessage(
  siteUrl: string,
  state: 'unlinked' | 'pending' | 'connected',
): string {
  const connectionInstructions = {
    unlinked: [
      'Как подключиться:',
      '1. На сайте откройте раздел «Мессенджеры».',
      '2. Нажмите «Подключить» и перейдите в бота по созданной ссылке.',
      '3. Запустите бота, затем вернитесь на сайт и подтвердите подключение.',
    ].join('\n'),
    pending:
      'Остался один шаг: вернитесь на сайт и подтвердите подключение этого аккаунта в разделе «Мессенджеры».',
    connected: 'Ваш аккаунт уже подключён.',
  };

  return [
    '👋 Здравствуйте! Это бот Земледела.',
    'Получайте сообщения по заявкам и отвечайте клиентам и исполнителям прямо здесь. Вся переписка сохраняется на сайте.',
    connectionInstructions[state],
    [
      'Как отвечать:',
      'Нажмите «Ответить здесь» под нужным уведомлением и напишите сообщение. Или выберите «Открыть чат на сайте», чтобы продолжить переписку там.',
    ].join('\n'),
    ...(siteUrl ? [`🌿 Земледел — ${siteUrl}`] : []),
  ].join('\n\n');
}
